/* ════════════════════════════════════════════════════════
   PRODUCT SCHEMA (JSON-LD) — pour Rich Snippets Google
════════════════════════════════════════════════════════ */
function injectProductSchema() {
    const path = resolveRealPath();
    if (!/\/products\/product\d+\.html/.test(path)) return;

    fetch('/products.data.json')
        .then(r => r.json())
        .then(data => {
            // Le fichier products.data.json se termine par un objet "settings" — on filtre
            const products = Array.isArray(data) ? data.filter(p => p.url) : [];
            const product = products.find(p => p.url === path);

            if (!product) {
                console.warn('[Product Schema] Aucun produit trouvé pour', path);
                return;
            }

            const seo = SEO_MAP[path] || {};
            const canonicalUrl = window.__canonicalUrl || ((seo.site_name === 'Curvafit' ? 'https://curvafit.com' : 'https://bbw4life.com') + path);

            // Construction de la liste des offres (une par variante active)
            const offers = (product.variants || [])
                .filter(v => v.active)
                .slice(0, 50) // Google limite le nombre d'offres affichées utilement
                .map(v => ({
                    '@type': 'Offer',
                    'sku': product.sku_internal || product.id,
                    'price': v.price,
                    'priceCurrency': product.currency || 'USD',
                    'availability': 'https://schema.org/InStock',
                    'url': canonicalUrl,
                    'itemCondition': 'https://schema.org/NewCondition'
                }));

            const schema = {
                '@context': 'https://schema.org',
                '@type': 'Product',
                'name': seo.title || product.title,
                'description': seo.description || product.description,
                'image': (product.media && product.media.length ? product.media : [product.image]),
                'sku': product.sku_internal || product.id,
                'brand': {
                    '@type': 'Brand',
                    'name': seo.site_name || 'BBW4LIFE'
                },
                'url': canonicalUrl
            };

            // Note moyenne — uniquement si on a des reviews réelles
            if (product.rating && product.reviews_count) {
                schema.aggregateRating = {
                    '@type': 'AggregateRating',
                    'ratingValue': product.rating,
                    'reviewCount': product.reviews_count,
                    'bestRating': '5',
                    'worstRating': '1'
                };
            }

            // Offre simple si peu de variantes, ou AggregateOffer si plusieurs prix différents
            const uniquePrices = [...new Set(offers.map(o => o.price))];

            if (offers.length === 0) {
                // Pas de variantes -> offre unique basée sur le prix produit
                schema.offers = {
                    '@type': 'Offer',
                    'price': product.price,
                    'priceCurrency': product.currency || 'USD',
                    'availability': 'https://schema.org/InStock',
                    'url': canonicalUrl,
                    'itemCondition': 'https://schema.org/NewCondition'
                };
            } else if (uniquePrices.length === 1) {
                // Toutes les variantes ont le même prix -> une seule offre suffit
                schema.offers = offers[0];
            } else {
                // Prix variables -> AggregateOffer avec min/max
                schema.offers = {
                    '@type': 'AggregateOffer',
                    'priceCurrency': product.currency || 'USD',
                    'lowPrice': Math.min(...uniquePrices),
                    'highPrice': Math.max(...uniquePrices),
                    'offerCount': offers.length,
                    'availability': 'https://schema.org/InStock',
                    'url': canonicalUrl
                };
            }

            
            const existing = document.getElementById('product-schema-ld');
            if (existing) existing.remove();

            const script = document.createElement('script');
            script.id = 'product-schema-ld';
            script.type = 'application/ld+json';
            script.text = JSON.stringify(schema);
            document.head.appendChild(script);
        })
        .catch(err => console.error('[Product Schema] Erreur de chargement:', err));
}


function injectGlobalHead() {
    return fetch('/src/components/head.html')
        .then(r => r.text())
        .then(html => {
            const temp = document.createElement('div');
            temp.innerHTML = html;
            Array.from(temp.children).forEach(el => {
                if (el.tagName === 'SCRIPT') {
                    // cart-page.js est déjà codé en dur en bas du body sur cart.html et
                    // les pages collections/*.html — éviter de le réinjecter en double ici.
                    if (el.src && /\/cart-page\.js(\?|$)/.test(el.src) &&
                        document.querySelector('script[src$="/cart-page.js"], script[src="cart-page.js"]')) {
                        return;
                    }
                    // Recrée le script pour forcer l'exécution
                    const s = document.createElement('script');
                    if (el.type) s.type = el.type;
                    if (el.src) s.src = el.src;
                    else s.textContent = el.textContent;
                    s.defer = el.defer;
                    document.head.appendChild(s);
                } else {
                    document.head.appendChild(el.cloneNode(true));
                }
            });
        })
        .catch(err => console.error('[Head] Failed to load head.html:', err));
        }

        
        function injectPageSEO() {
    const path = window.location.pathname;
    const pathWithHtml = path.endsWith('.html') ? path : path + '.html';

    let seo = SEO_MAP[path] || SEO_MAP[pathWithHtml];
    let rawPath = SEO_MAP[path] ? path : (SEO_MAP[pathWithHtml] ? pathWithHtml : null);
    const slugMap = window.CURVAFIT_SLUGS || window.BBW_SLUGS;

    // Pretty URL → retrouver le fichier HTML correspondant.
    if (!seo && slugMap) {
        const realPath = Object.keys(slugMap).find(
            key => slugMap[key] === path
        );
        if (realPath) {
            seo = SEO_MAP[realPath];
            rawPath = realPath;
        }
    }

    const seoSourcePath = rawPath || path;
    const isProductPage = /^\/products\/product\d+\.html$/.test(seoSourcePath);
    const isJournalArticle = /^\/blog\/article\d+\.html$/.test(seoSourcePath);
    if (!seo && (isProductPage || isJournalArticle)) {
        const descriptionMeta = document.querySelector('meta[name="description"]');
        const keywordsMeta = document.querySelector('meta[name="keywords"]');
        const imageMeta = document.querySelector('meta[property="og:image"]');
        seo = {
            title: document.title || 'Curvafit',
            description: descriptionMeta ? descriptionMeta.content : '',
            keywords: keywordsMeta ? keywordsMeta.content : '',
            og_image: imageMeta ? imageMeta.content : 'https://curvafit.com/img/curva-banner-1.png',
            site_name: 'Curvafit'
        };
        rawPath = seoSourcePath;
    }

    if (!seo) {
        seo = {
            title: 'BBW4LIFE — Beauty Has No Size | Plus Size Fashion',
            description: 'BBW4LIFE — Bold plus size fashion for curvy women. Beauty Has No Size. Shop dresses, swimwear, beauty and more.',
            keywords: 'BBW4LIFE, plus size fashion, curvy women, body positive fashion, beauty has no size',
            og_image: 'https://bbw4life.com/public/og-home.jpg'
        };
        rawPath = path;
    }

    // ── CANONICAL DYNAMIQUE : toujours la version pretty si elle existe ──
    let canonicalPath = path;
    if (rawPath && slugMap && slugMap[rawPath]) {
        canonicalPath = slugMap[rawPath];
    }
    const isHomePage = rawPath === '/' || rawPath === '/index' || rawPath === '/index.html';
    const canonicalUrl = isHomePage
        ? (seo.canonical || 'https://curvafit.com/')
        : (seo.site_name === 'Curvafit'
            ? (seo.canonical || 'https://curvafit.com' + canonicalPath)
            : 'https://bbw4life.com' + canonicalPath);
    window.__canonicalUrl = canonicalUrl;

    document.title = seo.title;
    window.__seoTitle = seo.title;
    document.dispatchEvent(new CustomEvent('seo:ready', { detail: { title: seo.title } }));

    function setMeta(selector, attr, value) {
        let el = document.querySelector(selector);
        if (!el) {
            el = document.createElement('meta');
            document.head.appendChild(el);
        }
        el.setAttribute(attr, value);
    }

    setMeta('meta[name="description"]',   'content', seo.description);
    setMeta('meta[name="keywords"]',      'content', seo.keywords);
    setMeta('meta[name="robots"]',        'content', seo.robots || 'index, follow');

    setMeta('meta[property="og:title"]',       'content', seo.title);
    setMeta('meta[property="og:description"]', 'content', seo.description);
    setMeta('meta[property="og:image"]',       'content', seo.og_image);
    setMeta('meta[property="og:url"]',         'content', canonicalUrl);
    if (seo.site_name) setMeta('meta[property="og:site_name"]', 'content', seo.site_name);

    setMeta('meta[name="twitter:title"]',       'content', seo.title);
    setMeta('meta[name="twitter:description"]', 'content', seo.description);
    setMeta('meta[name="twitter:image"]',       'content', seo.og_image);

    let canonical = document.querySelector('link[rel="canonical"]');
    if (!canonical) {
        canonical = document.createElement('link');
        canonical.rel = 'canonical';
        document.head.appendChild(canonical);
    }
    canonical.href = canonicalUrl;
}

/* ════════════════════════════════════════════════════════
   Résout le vrai chemin (/products/productN.html) à partir
   d'une pretty URL réécrite par pretty-url.js via
   history.replaceState() AVANT que ce script (defer) ne tourne.
   Même logique de fallback que injectPageSEO().
════════════════════════════════════════════════════════ */
function resolveRealPath() {
    const path = window.location.pathname;
    if (SEO_MAP[path]) return path;
    const pathWithHtml = path.endsWith('.html') ? path : path + '.html';
    if (SEO_MAP[pathWithHtml]) return pathWithHtml;
    const slugMap = window.CURVAFIT_SLUGS || window.BBW_SLUGS;
    if (slugMap) {
        const realPath = Object.keys(slugMap).find(
            key => slugMap[key] === path
        );
        if (realPath) return realPath;
    }
    return path;
}


/* ════════════════════════════════════════════════════════
   BREADCRUMB SCHEMA (JSON-LD) — hiérarchie logique du site
════════════════════════════════════════════════════════ */
function injectBreadcrumbSchema() {
    const path = resolveRealPath();
    const seo = SEO_MAP[path] || {};
    const isCurvafitPage = seo.site_name === 'Curvafit';
    const siteOrigin = isCurvafitPage ? 'https://curvafit.com' : 'https://bbw4life.com';
    const rawTitle = window.__seoTitle || document.title;
    const pageName = String(rawTitle).split('|')[0].trim();
    const canonicalUrl = window.__canonicalUrl || (siteOrigin + path);

    const items = [{ name: 'Home', url: siteOrigin + '/' }];

    if (/^\/products\/product\d+\.html/.test(path)) {
        items.push({ name: isCurvafitPage ? 'Guides' : 'Shop', url: isCurvafitPage ? 'https://curvafit.com/#curvafit-guides' : 'https://curvafit.com/collections/curvafit-all-products.html' });
        items.push({ name: pageName, url: canonicalUrl });
    } else if (/^\/blog\/blog\.html/.test(path)) {
        items.push({ name: 'Journal', url: canonicalUrl });
    } else if (/^\/blog\/article/.test(path)) {
        items.push({ name: 'Journal', url: 'https://bbw4life.com/blog/blog.html' });
        items.push({ name: pageName, url: canonicalUrl });
    } else if (/^\/policies\//.test(path) || /^\/collections\//.test(path) || /^\/page\//.test(path)) {
        items.push({ name: pageName, url: canonicalUrl });
    } else {
        return; // home page ou route inconnue — pas de fil d'Ariane à représenter
    }

    const schema = {
        '@context': 'https://schema.org',
        '@type': 'BreadcrumbList',
        'itemListElement': items.map((it, i) => ({
            '@type': 'ListItem',
            'position': i + 1,
            'name': it.name,
            'item': it.url
        }))
    };

    const existing = document.getElementById('breadcrumb-schema-ld');
    if (existing) existing.remove();
    const script = document.createElement('script');
    script.id = 'breadcrumb-schema-ld';
    script.type = 'application/ld+json';
    script.text = JSON.stringify(schema);
    document.head.appendChild(script);
}


/* ════════════════════════════════════════════════════════
   FAQ SCHEMA (JSON-LD) — page/faq.html uniquement
════════════════════════════════════════════════════════ */
function injectFaqSchema() {
    if (!/\/page\/faq\.html/.test(resolveRealPath())) return;
    const items = document.querySelectorAll('.faq-item');
    if (!items.length) return;

    const mainEntity = Array.from(items).map(item => {
        const q = item.querySelector('.faq-question span');
        const a = item.querySelector('.faq-answer-inner');
        if (!q || !a) return null;
        return {
            '@type': 'Question',
            'name': q.textContent.trim(),
            'acceptedAnswer': {
                '@type': 'Answer',
                'text': a.textContent.trim().replace(/\s+/g, ' ')
            }
        };
    }).filter(Boolean);

    if (!mainEntity.length) return;

    const schema = {
        '@context': 'https://schema.org',
        '@type': 'FAQPage',
        'mainEntity': mainEntity
    };

    const script = document.createElement('script');
    script.type = 'application/ld+json';
    script.text = JSON.stringify(schema);
    document.head.appendChild(script);
}


